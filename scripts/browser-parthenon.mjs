import assert from 'node:assert/strict';
import {mkdirSync,statSync} from 'node:fs';
import {chromium} from 'playwright';
const origin=process.env.SMOKE_URL||'http://127.0.0.1:4174/specimens/parthenon/';
mkdirSync('qa-parthenon',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
try{
 const page=await browser.newPage({viewport:{width:1536,height:960},deviceScaleFactor:1});
 const issues=[];page.on('pageerror',e=>issues.push(e.message));page.on('console',e=>{if(e.type()==='error')issues.push(e.text());});
 await page.emulateMedia({colorScheme:'dark'});
 await page.goto(origin,{waitUntil:'domcontentloaded',timeout:45000});
 assert.equal(await page.locator('#siteTheme').inputValue(),'system');
 assert.equal(await page.locator('html').getAttribute('data-resolved-theme'),'dark');
 await page.emulateMedia({colorScheme:'light'});
 await page.waitForFunction(()=>document.documentElement.dataset.resolvedTheme==='light');
 const lightColor=await page.locator('.inspector').evaluate(x=>getComputedStyle(x).backgroundColor);
 await page.locator('#siteTheme').selectOption('dark');
 assert.equal(await page.locator('html').getAttribute('data-resolved-theme'),'dark');
 assert.notEqual(lightColor,await page.locator('.inspector').evaluate(x=>getComputedStyle(x).backgroundColor));
 await page.reload({waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('#siteTheme').inputValue(),'dark');
 await page.locator('#siteTheme').selectOption('system');
 await page.waitForFunction(()=>document.querySelector('#count')?.textContent?.includes('individual selectable parts'),null,{timeout:65000});
 assert.equal(await page.locator('#error').isHidden(),true);
 assert.match(await page.locator('#count').innerText(),/536 individual selectable parts/);
 assert.equal(await page.evaluate(()=>window.__architectariumMetrics?.progressive),true,'Model must have a progressive build');
 assert.ok((await page.evaluate(()=>window.__architectariumMetrics?.buildMilliseconds))>0,'Missing build metric');
 assert.ok((await page.evaluate(()=>window.__architectariumMetrics?.firstBatchMilliseconds))>=0,'Missing first-batch performance metric');
 assert.ok(await page.locator('.interpretation-key').isVisible(),'Visitor fidelity classification must remain visible');
 assert.ok(await page.locator('#viewer').evaluate(el=>!!(el.getContext('webgl2')||el.getContext('webgl'))));
 assert.match(await page.locator('.fidelity').innerText(),/SCHEMATIC/);
 await page.locator('#search').fill('ionic capital');
 // Use the full physical ID search to inspect a child with physical dependencies.
 await page.locator('#search').fill('west-room/ionic/column-01/capital');
 assert.ok((await page.locator('.part-row').count())>0,'Missing Ionic capital instance');
 await page.locator('.part-row').first().click();
 assert.ok((await page.locator('#detail .instance-related button').count())>0,'Instance-to-instance relationships must navigate');
 await page.locator('#detail .instance-related button').first().click();
 assert.match(await page.locator('#detail h2').innerText(),/shaft/i);
 await page.locator('#search').fill('metope');
 assert.ok(await page.locator('.part-row').count()>=14,'Metope search failed');
 await page.locator('.part-row').first().click();
 assert.match(await page.locator('#detail h2').innerText(),/metope/i);
 assert.match(await page.locator('#detail').innerText(),/Evidence status/);
 assert.equal(await page.locator('#materials').getAttribute('aria-pressed'),'false');
 assert.equal(await page.evaluate(()=>window.__architectariumMetrics.materialMode),'study');
 await page.screenshot({path:'qa-parthenon/material-study.png'});
 await page.locator('#materials').click();
 await page.waitForFunction(()=>window.__architectariumMetrics.materialMode==='realistic');
 assert.equal(await page.locator('#materials').getAttribute('aria-pressed'),'true');
 assert.ok(await page.evaluate(()=>window.__architectariumMetrics.realisticTextureCount)>=4,'Detailed textures missing');
 await page.screenshot({path:'qa-parthenon/material-realistic.png'});
 await page.locator('#materials').click();
 assert.equal(await page.evaluate(()=>window.__architectariumMetrics.materialMode),'study');
 await page.locator('#roof').click();
 assert.equal(await page.locator('#roof').getAttribute('aria-pressed'),'true');
 await page.locator('#cutaway').click();
 assert.equal(await page.locator('#cutaway').getAttribute('aria-pressed'),'true');
 await page.locator('#sun').fill('10');
 const noHaze=await page.evaluate(()=>window.__architectariumAtmosphere);
 assert.equal(noHaze.enabled,false);
 assert.equal(noHaze.dustVisible,false);
 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 const clearAir=await page.screenshot({path:'qa-parthenon/atmosphere-off.png',animations:'disabled'});
 await page.locator('#atmos').click();
 assert.equal(await page.locator('#atmos').getAttribute('aria-pressed'),'true');
 const haze=await page.evaluate(()=>window.__architectariumAtmosphere);
 assert.equal(haze.enabled,true);
 assert.equal(haze.dustVisible,true);
 assert.ok(haze.fogDensity>=noHaze.fogDensity*2.5,'Atmosphere must substantially change scene haze');
 assert.ok(haze.particleCount>=800,'Atmospheric particles too sparse');
 assert.match(await page.locator('#atmosStatus').innerText(),/haze and sunlit dust/i);
 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 const thickAir=await page.screenshot({path:'qa-parthenon/atmosphere-on.png',animations:'disabled'});
 assert.ok(!thickAir.equals(clearAir),'Atmosphere must change rendered pixels');
 await page.locator('#atmos').click();
 assert.equal(await page.locator('#atmos').getAttribute('aria-pressed'),'false');
 assert.equal(await page.evaluate(()=>window.__architectariumAtmosphere.enabled),false);
 assert.match(await page.locator('#hour').innerText(),/10:00/);
 await page.locator('#reset').click();
 assert.equal(await page.locator('#roof').getAttribute('aria-pressed'),'false');
 assert.equal(await page.locator('#cutaway').getAttribute('aria-pressed'),'false');
 await page.locator('#walk').click();
 await page.waitForFunction(()=>document.querySelector('#walk')?.getAttribute('aria-pressed')==='true',null,{timeout:8000});
 await page.keyboard.down('w');await page.waitForTimeout(180);await page.keyboard.up('w');
 // Browser-native pointer unlock is the reliable headless equivalent of Escape.
 const locked=await page.evaluate(()=>Boolean(document.pointerLockElement));
 if(locked)await page.evaluate(()=>document.exitPointerLock());
 else await page.locator('#walk').click();
 await page.waitForFunction(()=>document.querySelector('#walk')?.getAttribute('aria-pressed')==='false',null,{timeout:8000});
 // Walk mode must be re-enterable without a page reload.
 await page.locator('#walk').click();
 await page.waitForFunction(()=>document.querySelector('#walk')?.getAttribute('aria-pressed')==='true',null,{timeout:8000});
 if(await page.evaluate(()=>Boolean(document.pointerLockElement)))await page.evaluate(()=>document.exitPointerLock());
 else await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.querySelector('#walk')?.getAttribute('aria-pressed')==='false',null,{timeout:8000});
 await page.locator('.part-row').first().click();
 await page.locator('#siteTheme').selectOption('light');
 await page.screenshot({path:'qa-parthenon/desktop-light.png',timeout:60000,animations:'disabled'});
 assert.ok(statSync('qa-parthenon/desktop-light.png').size>25000);
 await page.locator('#siteTheme').selectOption('system');
 await page.screenshot({path:'qa-parthenon/desktop.png',timeout:60000,animations:'disabled'});
 assert.ok(statSync('qa-parthenon/desktop.png').size>25000,'Desktop scene screenshot is small');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'qa-parthenon/mobile.png',timeout:60000,animations:'disabled'});
 assert.ok(statSync('qa-parthenon/mobile.png').size>18000,'Mobile scene screenshot is small');
 const dimensions=await page.evaluate(()=>({viewport:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(dimensions.scroll<=dimensions.viewport+3,'Mobile horizontal overflow: '+JSON.stringify(dimensions));
 assert.deepEqual(issues,[],'Unexpected browser errors');
 console.log('Parthenon WebGL scene, component search, picking, visibility, lighting and responsive layout passed.');
}finally{await browser.close();}
