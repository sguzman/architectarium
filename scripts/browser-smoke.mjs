import assert from 'node:assert/strict';
import {statSync,mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
const origin=process.env.SMOKE_URL||'http://127.0.0.1:4173/';
mkdirSync('qa-shots',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
let page;
try{
 page=await browser.newPage({viewport:{width:1536,height:1000},deviceScaleFactor:1});
 const exceptions=[];
 page.on('pageerror',e=>exceptions.push('pageerror: '+e.message));
 page.on('console',msg=>{if(msg.type()==='error')exceptions.push('console: '+msg.text());});
 await page.goto(origin,{waitUntil:'domcontentloaded',timeout:45000});
 await page.waitForFunction(()=>document.getElementById('sceneState')?.textContent?.includes('selectable'),null,{timeout:50000});
 assert.equal(await page.locator('#error').isHidden(),true,'Viewer reported an initialization error');
 assert.ok((await page.locator('#specimenList .specimen').count())>=5,'Missing specimen queue');
 assert.ok((await page.locator('#terms [data-concept]').count())>=40,'Missing ontology');
 const webgl=await page.locator('#view').evaluate(c=>!!(c.getContext('webgl2')||c.getContext('webgl')));
 assert.equal(webgl,true,'WebGL context unavailable');
 await page.locator('#search').fill('cornice');
 assert.equal(await page.locator('#terms button').count(),1,'Term search mismatch');
 await page.locator('#terms button').click();
 assert.match(await page.locator('#inspector h3').innerText(),/Cornice/i,'Term inspector mismatch');
 await page.locator('#roofToggle').click();
 assert.match(await page.locator('#roofToggle').innerText(),/Show roof/);
 await page.locator('#wallsToggle').click();
 assert.equal(await page.locator('#wallsToggle').getAttribute('aria-pressed'),'true');
 await page.locator('#daylight').fill('10');
 await page.locator('#dustToggle').click();
 await page.screenshot({path:'qa-shots/desktop.png',fullPage:true});
 assert.ok(statSync('qa-shots/desktop.png').size>20000,'Desktop screenshot unexpectedly small');
 await page.locator('#reset').click();
 assert.equal(await page.locator('#roofToggle').getAttribute('aria-pressed'),'false');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'qa-shots/mobile.png',fullPage:true});
 assert.ok(statSync('qa-shots/mobile.png').size>15000,'Mobile screenshot unexpectedly small');
 assert.equal(exceptions.length,0,'Browser JS errors: '+exceptions.join(' | '));
 console.log('Desktop + mobile 3D smoke passed; artifacts in qa-shots/');
}finally{await browser.close();}
