import assert from 'node:assert/strict';
import {statSync,mkdirSync} from 'node:fs';
import {chromium} from 'playwright';

const origin=process.env.SMOKE_URL||'http://127.0.0.1:4173/';
mkdirSync('qa-shots',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--disable-dev-shm-usage']});
try{
  const page=await browser.newPage({viewport:{width:1536,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
  await page.emulateMedia({colorScheme:'dark'});
  await page.goto(origin,{waitUntil:'domcontentloaded',timeout:45000});
  assert.equal(await page.locator('#siteTheme').inputValue(),'system','Default must be System');
  assert.equal(await page.locator('html').getAttribute('data-resolved-theme'),'dark');
  const darkBg=await page.locator('body').evaluate(e=>getComputedStyle(e).backgroundColor);
  await page.emulateMedia({colorScheme:'light'});
  await page.waitForFunction(()=>document.documentElement.dataset.resolvedTheme==='light');
  const lightBg=await page.locator('body').evaluate(e=>getComputedStyle(e).backgroundColor);
  assert.notEqual(lightBg,darkBg,'System preference must recolor the homepage');
  await page.locator('#siteTheme').selectOption('dark');
  assert.equal(await page.locator('html').getAttribute('data-resolved-theme'),'dark');
  await page.emulateMedia({colorScheme:'light'});
  assert.equal(await page.locator('html').getAttribute('data-resolved-theme'),'dark','Manual override must remain fixed');
  await page.reload({waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('#siteTheme').inputValue(),'dark','Manual preference should survive a reload');
  await page.locator('#siteTheme').selectOption('light');
  assert.equal(await page.locator('html').getAttribute('data-resolved-theme'),'light');
  await page.locator('#siteTheme').selectOption('system');
  await page.emulateMedia({colorScheme:'dark'});
  await page.waitForFunction(()=>document.documentElement.dataset.resolvedTheme==='dark');
  await page.waitForFunction(()=>document.getElementById('conceptCount')?.textContent!=='—',{timeout:45000});
  assert.ok(Number(await page.locator('#conceptCount').innerText())>=40);
  assert.equal(await page.locator('#publishedCount').innerText(),'1');
  assert.equal(await page.locator('#galleryContent .gallery-item').count(),1);
  assert.match(await page.locator('#galleryContent').innerText(),/Parthenon/);
  assert.equal(await page.locator('#view').count(),0,'Home page must remain an ontology browser, not a 3D preview');
  const route=await page.locator('#galleryContent .gallery-item').first().getAttribute('href');
  assert.equal(route,'./specimens/parthenon/');
  const exhibit=await page.request.get(new URL(route,origin).href);
  assert.equal(exhibit.status(),200,'Published exhibit must be served from generated GitHub Pages release');
  const data=await page.request.get(new URL('./specimens/parthenon/data/instances.json',origin).href);
  assert.equal(data.status(),200,'Public physical component data must be available');
  assert.equal((await data.json()).instances.length,482);
  assert.ok((await page.locator('#terms button.term').count())>=40,'Missing ontology terms');
  await page.locator('#search').fill('cornice');
  assert.ok((await page.locator('#terms button.term').count())>0,'Search returned nothing');
  await page.locator('#terms button.term').filter({hasText:'Cornice'}).first().click();
  assert.match(await page.locator('#inspector .term-name').innerText(),/Cornice/i);
  assert.ok((await page.locator('#inspector .related button').count())>=1,'Missing ontology connections');
  await page.locator('#inspector .related button').first().click();
  assert.ok((await page.locator('#inspector .term-name').innerText()).length>3);
  await page.locator('#search').fill('');
  await page.screenshot({path:'qa-shots/desktop.png',fullPage:true});
  assert.ok(statSync('qa-shots/desktop.png').size>12000);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'qa-shots/mobile.png',fullPage:true});
  assert.ok(statSync('qa-shots/mobile.png').size>10000);
  const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:window.innerWidth}));
  assert.ok(width.scroll<=width.viewport+2,'Mobile viewport has horizontal overflow: '+JSON.stringify(width));
  assert.deepEqual(errors,[],'Browser console/runtime errors');
  console.log('Desktop and mobile ontology-first website passed Chromium smoke.');
}finally{await browser.close();}
